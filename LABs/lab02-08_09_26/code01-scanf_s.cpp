
#include <stdio.h>

void main(){
  float k1,k2,b1,b2;      //объявляем переменные обозначающие k и b в ур-е y=kx+b, для двух прямых
  float x,y;              // соответственно сами координаты точки переснечения
  scanf_s("%f", &k1);     // ввод данных
  scanf_s("%f", &k2);
  scanf_s("%f", &b1);
  scanf_s("%f", &b2);
  x=(b1-b2) / (k2-k1);    //вычисляем x пересечения
  y=k1*x+b1;              //по найденному x находим y
  printf("Cordinati: %f, %f\n",x,y);   //выводим найденные данные, %f обозначет, что на это место встанет переменная float 
  scanf_s("%f", &b2);     // заглушка
}
